 await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent==='Shift+←'&&!b.disabled));
 assert(await draft.inputValue()==='手机未发送的问题','regaining control preserves draft');
 await page.request.get(base+'/fixture/offline');
 await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent==='Shift+←'&&b.disabled));
 before=(await state()).stdin.length;
 assert(await shift.isDisabled(),'disconnected input is disabled');
 await page.request.get(base+'/fixture/online');
