 after=await state();
 assert(after.stdin.length===before.stdin.length&&after.signals.length===before.signals.length,'physical TUI Ctrl+C cannot bypass the protected button');
 const shell='00000007-1111-4111-8111-111111111111';
 await page.goto(base+'/sessions/'+shell);
 const interrupt=page.getByRole('button',{name:'Ctrl+C',exact:true});
