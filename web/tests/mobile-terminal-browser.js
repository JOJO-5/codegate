 const readable=await page.evaluate(()=>{
  const luminance=color=>{const rgb=color.match(/[\d.]+/g).slice(0,3).map(n=>{const v=Number(n)/255;return v<=.04045?v/12.92:((v+.055)/1.055)**2.4});return rgb[0]*.2126+rgb[1]*.7152+rgb[2]*.0722};
  return [...document.querySelectorAll('.term__quick-keys button')].every(b=>{const s=getComputedStyle(b),a=luminance(s.color),z=luminance(s.backgroundColor);return(Math.max(a,z)+.05)/(Math.min(a,z)+.05)>=4.5});
 });
 assert(readable,'dark-theme key labels have readable contrast');
 before=await state();
