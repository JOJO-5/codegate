// Isolated browser checks; mock clipboard text and fixture sessions only.
async page => {
 const base='http://127.0.0.1:4198',id='00000002-1111-4111-8111-111111111111',checks=[],errors=[];
 const assert=(ok,name)=>{if(!ok)throw Error(name);checks.push(name)};
 page.on('pageerror',e=>errors.push(e.message));
 await page.emulateMedia({colorScheme:'light'});
 await page.setViewportSize({width:390,height:844});
 await page.goto(base+'/sessions/'+id);
 const toggle=page.getByRole('button',{name:'☰ 切换',exact:true});
 const sidebar=page.getByRole('complementary',{name:'会话工作区',exact:true});
 await page.getByRole('button',{name:'Shift+←',exact:true}).waitFor();
 await toggle.click();
 const inside=await page.evaluate(()=>{const a=document.querySelector('.term__sidebar').getBoundingClientRect(),b=document.querySelector('.term__workspace').getBoundingClientRect();return a.top>=b.top&&a.bottom<=b.bottom});
 assert(inside,'mobile switcher stays within actual workspace instead of covering header or composer');
 const close=sidebar.getByRole('button',{name:'关闭会话切换',exact:true});
 assert(await close.isVisible(),'mobile switcher provides an explicit close action');
 await page.screenshot({path:'mobile-terminal-switcher-after.png',animations:'disabled'});
 await close.click();
 assert(await toggle.getAttribute('aria-expanded')==='false','close action collapses switcher');
 assert(await toggle.evaluate(e=>e===document.activeElement),'close restores focus to opener');
 await toggle.click();await page.keyboard.press('Escape');
 assert(await toggle.getAttribute('aria-expanded')==='false','keyboard Escape closes switcher');
 await toggle.click();await page.locator('.term__switcher-backdrop').click({position:{x:350,y:20}});
 assert(await toggle.getAttribute('aria-expanded')==='false','outside tap closes switcher without touching terminal');
 await toggle.click();await sidebar.locator('.term__session-link--active').click();
 assert(await toggle.getAttribute('aria-expanded')==='false','selecting current session returns to terminal');
 await page.getByRole('button',{name:'更多操作',exact:true}).click();
 await toggle.click();
 for(const [width,height] of [[320,360],[390,844],[640,800]]){
  await page.setViewportSize({width,height});
  const fits=await page.evaluate(()=>{const a=document.querySelector('.term__sidebar').getBoundingClientRect(),b=document.querySelector('.term__workspace').getBoundingClientRect();return a.top>=b.top&&a.bottom<=b.bottom&&a.right<=innerWidth});
  assert(fits,'switcher follows expanded footer at '+width+'x'+height);
 }
 await page.setViewportSize({width:1280,height:900});
 assert(await sidebar.isVisible()&&!await close.isVisible(),'desktop keeps persistent workspace sidebar');
 await page.setViewportSize({width:390,height:844});await close.click();
 await page.getByRole('button',{name:'收起操作',exact:true}).click();
 await page.evaluate(()=>{
  window.__clipboardReads=0;
  Object.defineProperty(navigator,'clipboard',{configurable:true,value:{readText:()=>{
   window.__clipboardReads++;
   return new Promise((resolve,reject)=>{window.__finishClipboard=resolve;window.__failClipboard=reject});
  }}});
 });
 const paste=page.getByRole('button',{name:'粘贴',exact:true});
 const preview=page.getByRole('textbox',{name:'确认要粘贴的文字',exact:true});
 const panel=page.locator('.clipboard-panel').filter({has:preview});
 await paste.click();
 assert(await page.getByText('正在读取剪贴板…',{exact:true}).isVisible(),'clipboard permission wait has visible status');
 assert(await paste.isDisabled(),'pending clipboard read prevents duplicate requests');
 assert(await preview.evaluate(e=>e===document.activeElement),'paste preview receives focus');
 await page.screenshot({path:'mobile-terminal-paste-after.png',animations:'disabled'});
 await preview.fill('手动输入优先');
 await page.evaluate(()=>window.__finishClipboard('过期剪贴板'));
 assert(await preview.inputValue()==='手动输入优先','late read cannot replace manual editing');
 await panel.getByRole('button',{name:'取消',exact:true}).click();await paste.click();
 assert(await preview.inputValue()==='手动输入优先','reopening keeps unsent paste preview');
 assert(await page.evaluate(()=>window.__clipboardReads)===1,'reopening retained preview does not re-read clipboard');
 await preview.fill('');
 await panel.getByRole('button',{name:'重新读取剪贴板',exact:true}).click();
 await panel.getByRole('button',{name:'取消',exact:true}).click();
 assert(await paste.evaluate(e=>e===document.activeElement),'cancelling a pending read returns focus to paste opener');
 await page.evaluate(()=>window.__finishClipboard('已取消的内容'));
 assert(await preview.count()===0,'cancelled read cannot reopen panel');
 await paste.click();await page.evaluate(()=>window.__failClipboard(Error('permission denied')));
 await page.getByText('浏览器未允许读取剪贴板，请在下方输入框手动粘贴。',{exact:true}).waitFor();
 assert(await preview.isEnabled(),'denied clipboard permission preserves manual recovery');
 await panel.getByRole('button',{name:'重新读取剪贴板',exact:true}).click();
 await page.evaluate(()=>window.__finishClipboard(''));
 await page.getByText('剪贴板中没有文字，请在下方输入框手动粘贴。',{exact:true}).waitFor();
 assert(await preview.inputValue()==='','empty clipboard has a distinct recovery message');
 await preview.fill('保留未粘贴内容');
 const confirm=panel.getByRole('button',{name:'粘贴到终端',exact:true});
 await page.request.get(base+'/fixture/offline');
 await page.waitForFunction(()=>document.querySelector('.term__quick-keys button').disabled);
 assert(await confirm.isDisabled(),'disconnected preview cannot send text');
 assert(await preview.inputValue()==='保留未粘贴内容','disconnect retains preview for manual retry');
 const before=(await (await page.request.get(base+'/fixture/state')).json()).stdin.length;
 await page.request.get(base+'/fixture/online');
 await page.waitForFunction(()=>!document.querySelector('.term__quick-keys button').disabled,null,{timeout:30000});
 assert((await (await page.request.get(base+'/fixture/state')).json()).stdin.length===before,'reconnect never automatically pastes pending preview');
 await preview.fill('含控制字符\x03');await confirm.click();
 await page.getByText('粘贴内容含 Ctrl+C 控制字符，请移除后重试。',{exact:true}).waitFor();
 assert(await preview.inputValue()==='含控制字符\x03','blocked control character preserves editable paste preview');
 assert((await (await page.request.get(base+'/fixture/state')).json()).stdin.length===before,'paste cannot bypass TUI Ctrl+C protection');
 await preview.fill('保留未粘贴内容');
 await confirm.click();
 await page.waitForFunction(async count=>(await fetch('/fixture/state').then(r=>r.json())).stdin.length>count,before);
 const after=await (await page.request.get(base+'/fixture/state')).json();
 assert(after.stdin.length===before+1,'confirmed paste sends one frame');
 assert(new TextDecoder().decode(new Uint8Array(after.stdin.at(-1)))==='保留未粘贴内容','confirmed paste adds no Enter');
 assert(await preview.count()===0,'confirmed paste closes preview');
 assert(await paste.evaluate(e=>e===document.activeElement),'paste confirmation returns focus to its opener');
 await page.getByRole('button',{name:'更多操作',exact:true}).click();
 await page.getByRole('button',{name:'查找',exact:true}).click();
 const search=page.getByRole('textbox',{name:'查找终端输出',exact:true});
 assert(await search.isVisible(),'terminal search has an accessible name');
 assert(await search.evaluate(e=>e===document.activeElement),'search entry receives focus');
 await search.fill('Codex');
 assert(await page.getByRole('button',{name:'查找上一个',exact:true}).isEnabled()&&await page.getByRole('button',{name:'查找下一个',exact:true}).isEnabled(),'search arrows have distinct accessible labels');
 await page.keyboard.press('Escape');
 assert(await search.count()===0,'Escape closes terminal search');
 assert(errors.length===0,'no browser JavaScript errors');
 return{checks:checks.length,names:checks,realAgentActions:0,modelCalls:0};
}
